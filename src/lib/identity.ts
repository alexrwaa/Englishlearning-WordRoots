/**
 * Morpheme identity index — the single place that answers "which morpheme does
 * this spelling mean?" (docs/DATA_IDENTITY.md).
 *
 * The lexicon is keyed by ID, not by spelling. A surface form maps to *one or
 * more* IDs: `plac` is both Latin "please" and Greek "flat". Every caller that
 * only has a spelling must either pass a hint or accept `ambiguous: true`. The
 * index never falls back to "first in the array", because that silently picks a
 * different linguistic entity depending on file order.
 *
 * This module is pure: no JSON imports, no bundler glob. `src/lib/content.ts`
 * loads `forms.json` from disk and hands it in, and the Node scripts read the
 * same files with `fs`. That keeps the resolver identical in app and CI.
 */
import type { LangOrigin, Morpheme } from './types';

/** `{ form: [id…] }`, generated by `scripts/identity-migrate.ts`. */
export interface FormIndex {
  [form: string]: string[];
}

export interface ResolveHint {
  /** Source language of the intended morpheme: `Lat`, `Gk`, `L`, `G`, … */
  origin?: string;
  /** The sense wanted, in English (`please`, `flat`, `not`, `into`, `two`). */
  glossEn?: string;
  /** `senseKey` of the intended record, when the UI already knows it. */
  senseKey?: string;
  /** Concept / morpheme IDs a lesson lists as taught context. */
  lessonConcepts?: string[];
  /** The other surface parts of the word being analysed. */
  wordParts?: string[];
}

export interface Resolution {
  /** Only set when the form has exactly one candidate after hints. */
  id?: string;
  /** Every ID this spelling can stand for (empty when unknown). */
  candidates: string[];
  ambiguous: boolean;
}

export interface IdentityIndex {
  readonly forms: FormIndex;
  /** All IDs recorded for a spelling (form, allomorph or formKey). */
  idsForForm(form: string): string[];
  byId(id: string): Morpheme | undefined;
  all(): readonly Morpheme[];
  /** Resolve a spelling, optionally narrowing it with a hint. */
  resolve(form: string, hint?: ResolveHint): Resolution;
  /** IDs of the lexical family the morpheme belongs to (self included). */
  familyOf(id: string): string[];
  /** Same spelling, different linguistic entity (self excluded). */
  homographsOf(id: string): string[];
  isAmbiguous(form: string): boolean;
  stats(): { morphemes: number; forms: number; ambiguousForms: string[] };
}

const ORIGIN_ALIASES: Record<string, LangOrigin> = {
  l: 'Lat',
  lat: 'Lat',
  latin: 'Lat',
  g: 'Gk',
  gk: 'Gk',
  gr: 'Gk',
  greek: 'Gk',
  oe: 'OE',
  'old english': 'OE',
  anglian: 'OE',
  me: 'ME',
  'middle english': 'ME',
  f: 'Fr',
  fr: 'Fr',
  french: 'Fr',
  of: 'Fr',
  norse: 'Norse',
  on: 'Norse',
  it: 'It',
  italian: 'It',
  sp: 'Sp',
  spanish: 'Sp',
  ger: 'Ger',
  german: 'Ger',
  ar: 'Ar',
  arabic: 'Ar',
  unknown: 'unknown',
  '?': 'unknown',
};

const GENERIC_FAMILIES = new Set(['fam-prefix', 'fam-suffix']);

/** Lowercase, drop the hyphens that mark position (`in-`, `-tion`). */
export function normalizeForm(form: string | undefined | null): string {
  if (!form) return '';
  return form
    .trim()
    .toLowerCase()
    .replace(/^[-‐‑–—]+/, '')
    .replace(/[-‐‑–—]+$/, '');
}

/** `L` / `Latin` / `lat.` all mean the same origin. */
export function normalizeOrigin(raw: string | undefined | null): LangOrigin | undefined {
  if (!raw) return undefined;
  const key = raw.trim().toLowerCase().replace(/\.$/, '');
  return ORIGIN_ALIASES[key];
}

export function glossVariants(gloss: string | undefined): string[] {
  if (!gloss) return [];
  return gloss
    .toLowerCase()
    .split(/[,;/|()[\]{}、，；（）]/)
    .map((s) => s.trim().replace(/^to\s+/, '').replace(/^[-‐‑–—]+|[-‐‑–—]+$/g, ''))
    .filter((s) => s.length > 0 && s !== 'a' && s !== 'n');
}

/**
 * Shortest label that distinguishes one record from its homographs.
 * `glossEn` first (English is the disambiguator), then the Chinese gloss.
 */
export function senseKeyOf(m: Morpheme): string {
  const variants = glossVariants(m.glossEn);
  const fallback = glossVariants(m.glossZh);
  const key = variants[0] ?? fallback[0] ?? normalizeForm(m.form);
  return key.replace(/\s+/g, ' ').slice(0, 32);
}

/**
 * Does `haystack` contain `needle` as a *word*, not as a fragment?
 * Latin script needs a boundary check (`intolerable` contains `into`, but is
 * not the sense "into"); CJK has no spaces, so a plain substring is used.
 */
export function glossContains(haystack: string, needle: string): boolean {
  if (!needle) return false;
  const ascii = /^[\x20-\x7e]+$/.test(needle);
  if (!ascii) return haystack.includes(needle);
  const escaped = needle.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(`(^|[^a-z])${escaped}($|[^a-z])`, 'i').test(haystack);
}

function glossMatches(m: Morpheme, wanted: string): boolean {
  const target = wanted.trim().toLowerCase();
  if (!target) return false;
  for (const own of [m.glossEn, m.senseKey, m.glossZh]) {
    for (const variant of glossVariants(own)) {
      if (variant === target) return true;
      // Containment only for words long enough to be meaningful; "in" must not
      // match every gloss containing those two letters.
      if (target.length >= 3 && glossContains(variant, target)) return true;
      if (variant.length >= 3 && glossContains(target, variant)) return true;
    }
  }
  return false;
}

/**
 * Build the index from the lexicon plus the generated form index.
 *
 * Two layers, on purpose:
 *   • canonical  — `m.form`, the published identity map (`forms.json`);
 *   • variants   — `m.allomorphs`, only consulted when no record owns the
 *                  spelling canonically (so `im-` is not forced to choose
 *                  between every prefix that lists it as a variant).
 *
 * `forms` is authoritative for canonical spellings; allomorphs always come from
 * the records themselves, so a stale forms.json cannot hide `im-` / `il-`.
 */
export function loadIdentity(morphemes: Morpheme[], forms?: FormIndex): IdentityIndex {
  const byIdMap = new Map<string, Morpheme>();
  for (const m of morphemes) byIdMap.set(m.id, m);

  const canonical: FormIndex = {};
  const variants: FormIndex = {};
  const push = (target: FormIndex, form: string | undefined, id: string) => {
    const key = normalizeForm(form);
    if (!key) return;
    const list = target[key] ?? (target[key] = []);
    if (!list.includes(id)) list.push(id);
  };

  if (forms) {
    for (const [form, ids] of Object.entries(forms)) {
      for (const id of ids) push(canonical, form, id);
    }
  }
  for (const m of morphemes) {
    push(canonical, m.form, m.id);
    push(canonical, m.formKey, m.id);
    for (const alt of m.allomorphs ?? []) push(variants, alt, m.id);
  }
  // Deterministic order: lexicographic by ID, never by file order.
  for (const key of Object.keys(canonical)) canonical[key].sort();
  for (const key of Object.keys(variants)) variants[key].sort();

  const idsForForm = (form: string): string[] => {
    const key = normalizeForm(form);
    const exact = canonical[key];
    if (exact && exact.length > 0) return exact;
    return variants[key] ?? [];
  };

  const homographsOf = (id: string): string[] => {
    const m = byIdMap.get(id);
    if (!m) return [];
    const declared = (m.homographs ?? []).filter((other) => other !== id && byIdMap.has(other));
    const sameSpelling = idsForForm(m.formKey ?? m.form).filter((other) => other !== id);
    return [...new Set([...declared, ...sameSpelling])].sort();
  };

  const familyOf = (id: string): string[] => {
    const m = byIdMap.get(id);
    if (!m) return [];
    const family = m.familyId;
    if (!family || GENERIC_FAMILIES.has(family)) return [id];
    return morphemes
      .filter((other) => other.familyId === family)
      .map((other) => other.id)
      .sort();
  };

  const resolve = (form: string, hint?: ResolveHint): Resolution => {
    const candidates = idsForForm(form).filter((id) => byIdMap.has(id));
    if (candidates.length === 0) return { candidates: [], ambiguous: false };
    if (candidates.length === 1) return { id: candidates[0], candidates, ambiguous: false };

    let pool = candidates;
    /** A hint may only narrow the pool; a hint that matches nothing is ignored. */
    const narrow = (keep: string[]) => {
      if (keep.length > 0 && keep.length < pool.length) pool = keep;
    };

    if (hint?.origin) {
      const origin = normalizeOrigin(hint.origin);
      if (origin) narrow(pool.filter((id) => byIdMap.get(id)?.origin === origin));
    }
    if (hint?.senseKey) {
      const key = hint.senseKey.trim().toLowerCase();
      narrow(pool.filter((id) => (byIdMap.get(id)?.senseKey ?? '').toLowerCase() === key));
    }
    if (hint?.glossEn) {
      narrow(pool.filter((id) => glossMatches(byIdMap.get(id) as Morpheme, hint.glossEn as string)));
    }
    if (hint?.lessonConcepts?.length) {
      const refs = new Set(hint.lessonConcepts.map((r) => r.toLowerCase()));
      narrow(
        pool.filter((id) => {
          const m = byIdMap.get(id);
          if (!m) return false;
          return [id, m.formKey, m.senseKey, normalizeForm(m.form)].some(
            (key) => key && refs.has(key.toLowerCase()),
          );
        }),
      );
    }
    if (hint?.wordParts?.length) {
      const families = new Set<string>();
      for (const part of hint.wordParts) {
        for (const id of idsForForm(part)) {
          const family = byIdMap.get(id)?.familyId;
          if (family && !GENERIC_FAMILIES.has(family)) families.add(family);
        }
      }
      if (families.size > 0) {
        narrow(pool.filter((id) => {
          const family = byIdMap.get(id)?.familyId;
          return Boolean(family && families.has(family));
        }));
      }
    }

    if (pool.length === 1) return { id: pool[0], candidates, ambiguous: false };
    return { candidates, ambiguous: true };
  };

  return {
    forms: canonical,
    idsForForm,
    byId: (id) => byIdMap.get(id),
    all: () => morphemes,
    resolve,
    familyOf,
    homographsOf,
    isAmbiguous: (form) => idsForForm(form).length > 1,
    stats: () => ({
      morphemes: morphemes.length,
      forms: Object.keys(canonical).length,
      ambiguousForms: Object.keys(canonical)
        .filter((form) => (canonical[form] ?? []).length > 1)
        .sort(),
    }),
  };
}
