def build():
    entries = []
    seen = set()
    for form, typ, origin, zh, en, examples, allomorphs, note in T:
        if not form or form in seen:
            continue
        seen.add(form)
        prefix = {"prefix": "px", "root": "rx", "suffix": "sx", "combining": "cx"}[typ]
        entry = {
            "id": f"{prefix}-{form}",
            "form": form,
            "type": typ,
            "origin": origin,
            "glossZh": zh,
            "glossEn": en,
            "allomorphs": allomorphs,
            "examples": examples,
        }
        if note:
            entry["note"] = note
        src = {"prefix": "S1", "root": "S1", "suffix": "S1", "combining": "S2"}[typ]
        title, detail = S[src]
        entry["sources"] = [{"id": src, "title": title, "detail": detail}]
        entries.append(entry)

    entries.sort(key=lambda e: (e["type"], e["form"]))
    with open(OUT, "w", encoding="utf-8") as f:
        json.dump(entries, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"wrote {len(entries)} morphemes to {OUT}")


if __name__ == "__main__":
    build()
